import { useCallback, useEffect, useState } from "react";
import axios from "axios";
import { AlertTriangle, ChevronLeft, ChevronRight, RefreshCw } from "lucide-react";

const PAGE_SIZE = 25;
const SEVERITIES = ["", "CRITICAL", "HIGH", "MEDIUM", "LOW"];

function display(value, fallback = "—") {
  if (value == null || value === "") return fallback;
  if (typeof value === "object") return JSON.stringify(value);
  return String(value);
}

function severityTone(severity) {
  const value = String(severity || "").toUpperCase();
  if (["CRITICAL", "HIGH"].includes(value)) return "danger";
  if (value === "MEDIUM") return "warning";
  if (value === "LOW") return "success";
  return "neutral";
}

export default function IntelligencePage() {
  const [findings, setFindings] = useState([]);
  const [pagination, setPagination] = useState({ page: 1, total_count: 0, total_pages: 0 });
  const [page, setPage] = useState(1);
  const [severity, setSeverity] = useState("");
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");

  const loadFindings = useCallback(async () => {
    setLoading(true);
    setError("");
    try {
      const response = await axios.get("/api/findings", {
        params: { page, page_size: PAGE_SIZE, ...(severity && { severity }) },
        timeout: 15000,
      });
      setFindings(Array.isArray(response.data?.data) ? response.data.data : []);
      setPagination(response.data?.pagination || { page, total_count: 0, total_pages: 0 });
    } catch (requestError) {
      setFindings([]);
      setError(
        requestError.response?.data?.error?.message ||
        requestError.message ||
        "The Exasol intelligence view could not be reached."
      );
    } finally {
      setLoading(false);
    }
  }, [page, severity]);

  useEffect(() => {
    const timer = window.setTimeout(loadFindings, 0);
    return () => window.clearTimeout(timer);
  }, [loadFindings]);

  return (
    <>
      <div className="page-intro">
        <div>
          <h1>Intelligence findings</h1>
          <p>Read-only findings generated by the Exasol intelligence engine from OPS_INTEL.V_FINDINGS.</p>
        </div>
        <div className="actions">
          <label className="intelligence-filter">
            Severity
            <select value={severity} onChange={(event) => { setPage(1); setSeverity(event.target.value); }}>
              {SEVERITIES.map((value) => <option key={value} value={value}>{value || "All severities"}</option>)}
            </select>
          </label>
          <button type="button" className="btn" onClick={loadFindings} disabled={loading}>
            <RefreshCw size={14} /> Refresh
          </button>
        </div>
      </div>

      {error && <div className="notice"><AlertTriangle size={16} /> {error}</div>}

      <div className="grid metrics-grid intelligence-summary">
        <div className="card"><div className="metric-top">Matching findings</div><div className="metric-value">{pagination.total_count ?? 0}</div><div className="metric-bottom">From the curated Exasol view</div></div>
        <div className="card"><div className="metric-top">Current page</div><div className="metric-value">{pagination.page || page} / {pagination.total_pages || 0}</div><div className="metric-bottom">{findings.length} findings shown</div></div>
      </div>

      <div className="card intelligence-card">
        <div className="intelligence-table-wrap">
          <table className="intelligence-table">
            <thead><tr><th>Finding</th><th>Severity</th><th>Affected entity</th><th>Evidence</th><th>Recommended action</th></tr></thead>
            <tbody>
              {loading && !findings.length ? <tr><td colSpan="5" className="intelligence-empty">Loading Exasol findings…</td></tr> : null}
              {!loading && !error && !findings.length ? <tr><td colSpan="5" className="intelligence-empty">No findings match this filter.</td></tr> : null}
              {findings.map((finding) => (
                <tr key={finding.finding_id}>
                  <td><strong>{display(finding.finding_type, "Finding").replaceAll("_", " ")}</strong><small>{display(finding.finding_id)}</small></td>
                  <td><span className={`badge ${severityTone(finding.severity)}`}>{display(finding.severity, "Unknown")}</span></td>
                  <td>{display(finding.affected_entity?.id)}<small>{display(finding.affected_entity?.type, "")}</small></td>
                  <td>{display(finding.evidence, "No evidence supplied")}</td>
                  <td>{display(finding.recommended_action, "Review source evidence")}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
        <div className="intelligence-pager">
          <span>Page {pagination.page || page} of {pagination.total_pages || 0} · {pagination.total_count || 0} findings</span>
          <div className="actions">
            <button type="button" className="btn" onClick={() => setPage((current) => Math.max(1, current - 1))} disabled={page <= 1 || loading}><ChevronLeft size={14} /> Previous</button>
            <button type="button" className="btn" onClick={() => setPage((current) => current + 1)} disabled={page >= pagination.total_pages || loading}>Next <ChevronRight size={14} /></button>
          </div>
        </div>
      </div>
    </>
  );
}
