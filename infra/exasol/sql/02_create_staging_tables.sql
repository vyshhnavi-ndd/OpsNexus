-- Module 1 schema_version 2.0.0, one table per operational CSV.
-- JSON is retained as VARCHAR because the CSV contract carries JSON text.
-- Exasol supports DECIMAL precision up to 36, so high-precision numeric fields use DECIMAL(36,12).
-- bundle_id is deliberately not added: staging preserves the source columns exactly.

CREATE TABLE IF NOT EXISTS OPS_STAGE.STG_DATA_SOURCES (
  SOURCE_ID VARCHAR(200) NOT NULL,
  SOURCE_NAME VARCHAR(2000) NOT NULL,
  SOURCE_TYPE VARCHAR(200) NOT NULL,
  CLASSIFICATION VARCHAR(200) NOT NULL,
  SCHEMA_VERSION VARCHAR(50) NOT NULL,
  PRIMARY KEY (SOURCE_ID)
);

CREATE TABLE IF NOT EXISTS OPS_STAGE.STG_PIPELINE_DEFINITIONS (
  PIPELINE_ID VARCHAR(200) NOT NULL,
  PIPELINE_NAME VARCHAR(2000) NOT NULL,
  SOURCE_ID VARCHAR(200) NOT NULL,
  SCHEMA_VERSION VARCHAR(50) NOT NULL,
  PRIMARY KEY (PIPELINE_ID),
  FOREIGN KEY (SOURCE_ID) REFERENCES OPS_STAGE.STG_DATA_SOURCES (SOURCE_ID)
);

CREATE TABLE IF NOT EXISTS OPS_STAGE.STG_DATASETS (
  DATASET_ID VARCHAR(200) NOT NULL,
  DATASET_NAME VARCHAR(2000) NOT NULL,
  "DOMAIN" VARCHAR(200) NOT NULL,
  SOURCE_ID VARCHAR(200) NOT NULL,
  SCHEMA_VERSION VARCHAR(50) NOT NULL,
  PRIMARY KEY (DATASET_ID),
  FOREIGN KEY (SOURCE_ID) REFERENCES OPS_STAGE.STG_DATA_SOURCES (SOURCE_ID)
);

CREATE TABLE IF NOT EXISTS OPS_STAGE.STG_QUALITY_CHECKS (
  QUALITY_CHECK_ID VARCHAR(200) NOT NULL,
  DATASET_ID VARCHAR(200) NOT NULL,
  CHECK_TYPE VARCHAR(200) NOT NULL,
  DESCRIPTION VARCHAR(2000) NOT NULL,
  THRESHOLD_JSON VARCHAR(2000) NOT NULL,
  SCHEMA_VERSION VARCHAR(50) NOT NULL,
  PRIMARY KEY (QUALITY_CHECK_ID),
  FOREIGN KEY (DATASET_ID) REFERENCES OPS_STAGE.STG_DATASETS (DATASET_ID)
);

CREATE TABLE IF NOT EXISTS OPS_STAGE.STG_DEPENDENCIES (
  DEPENDENCY_ID VARCHAR(200) NOT NULL,
  UPSTREAM_PIPELINE_ID VARCHAR(200) NOT NULL,
  DOWNSTREAM_PIPELINE_ID VARCHAR(200) NOT NULL,
  DEPENDENCY_TYPE VARCHAR(200) NOT NULL,
  SCHEMA_VERSION VARCHAR(50) NOT NULL,
  PRIMARY KEY (DEPENDENCY_ID),
  FOREIGN KEY (UPSTREAM_PIPELINE_ID) REFERENCES OPS_STAGE.STG_PIPELINE_DEFINITIONS (PIPELINE_ID),
  FOREIGN KEY (DOWNSTREAM_PIPELINE_ID) REFERENCES OPS_STAGE.STG_PIPELINE_DEFINITIONS (PIPELINE_ID)
);

CREATE TABLE IF NOT EXISTS OPS_STAGE.STG_SCENARIO_METADATA (
  SCENARIO_INSTANCE_ID VARCHAR(200) NOT NULL,
  SCENARIO_TYPE VARCHAR(200) NOT NULL,
  DESCRIPTION VARCHAR(2000) NOT NULL,
  SEED DECIMAL(18,0) NOT NULL,
  SCHEMA_VERSION VARCHAR(50) NOT NULL,
  PRIMARY KEY (SCENARIO_INSTANCE_ID)
);

CREATE TABLE IF NOT EXISTS OPS_STAGE.STG_PIPELINE_RUNS (
  RUN_ID VARCHAR(200) NOT NULL,
  PIPELINE_ID VARCHAR(200) NOT NULL,
  SCENARIO_INSTANCE_ID VARCHAR(200) NOT NULL,
  STATUS VARCHAR(200) NOT NULL,
  STARTED_AT TIMESTAMP NOT NULL,
  ENDED_AT TIMESTAMP,
  DURATION_SECONDS DECIMAL(18,0),
  SCHEMA_VERSION VARCHAR(50) NOT NULL,
  PRIMARY KEY (RUN_ID),
  FOREIGN KEY (PIPELINE_ID) REFERENCES OPS_STAGE.STG_PIPELINE_DEFINITIONS (PIPELINE_ID),
  FOREIGN KEY (SCENARIO_INSTANCE_ID) REFERENCES OPS_STAGE.STG_SCENARIO_METADATA (SCENARIO_INSTANCE_ID)
);

CREATE TABLE IF NOT EXISTS OPS_STAGE.STG_DATASET_OBSERVATIONS (
  OBSERVATION_ID VARCHAR(200) NOT NULL,
  DATASET_ID VARCHAR(200) NOT NULL,
  RUN_ID VARCHAR(200) NOT NULL,
  SCENARIO_INSTANCE_ID VARCHAR(200) NOT NULL,
  OBSERVED_AT TIMESTAMP NOT NULL,
  WINDOW_START TIMESTAMP NOT NULL,
  WINDOW_END TIMESTAMP NOT NULL,
  ROW_COUNT DECIMAL(18,0) NOT NULL,
  EXPECTED_ROW_COUNT DECIMAL(18,0) NOT NULL,
  FRESHNESS_LAG_SECONDS DECIMAL(18,0) NOT NULL,
  COMPLETENESS_RATIO DECIMAL(18,6) NOT NULL,
  METRIC_NAME VARCHAR(200) NOT NULL,
  METRIC_VALUE DECIMAL(36,12) NOT NULL,
  SCHEMA_VERSION VARCHAR(50) NOT NULL,
  PRIMARY KEY (OBSERVATION_ID),
  FOREIGN KEY (DATASET_ID) REFERENCES OPS_STAGE.STG_DATASETS (DATASET_ID),
  FOREIGN KEY (RUN_ID) REFERENCES OPS_STAGE.STG_PIPELINE_RUNS (RUN_ID),
  FOREIGN KEY (SCENARIO_INSTANCE_ID) REFERENCES OPS_STAGE.STG_SCENARIO_METADATA (SCENARIO_INSTANCE_ID)
);

CREATE TABLE IF NOT EXISTS OPS_STAGE.STG_QUALITY_RESULTS (
  QUALITY_RESULT_ID VARCHAR(200) NOT NULL,
  QUALITY_CHECK_ID VARCHAR(200) NOT NULL,
  OBSERVATION_ID VARCHAR(200) NOT NULL,
  "RESULT" VARCHAR(200) NOT NULL,
  MEASURED_VALUE DECIMAL(36,12),
  EXPECTED_VALUE DECIMAL(36,12),
  SCHEMA_VERSION VARCHAR(50) NOT NULL,
  PRIMARY KEY (QUALITY_RESULT_ID),
  FOREIGN KEY (QUALITY_CHECK_ID) REFERENCES OPS_STAGE.STG_QUALITY_CHECKS (QUALITY_CHECK_ID),
  FOREIGN KEY (OBSERVATION_ID) REFERENCES OPS_STAGE.STG_DATASET_OBSERVATIONS (OBSERVATION_ID)
);

CREATE TABLE IF NOT EXISTS OPS_STAGE.STG_BUSINESS_KPIS (
  KPI_ID VARCHAR(200) NOT NULL,
  SCENARIO_INSTANCE_ID VARCHAR(200) NOT NULL,
  OBSERVATION_ID VARCHAR(200) NOT NULL,
  KPI_NAME VARCHAR(2000) NOT NULL,
  "DOMAIN" VARCHAR(200) NOT NULL,
  DATASET_ID VARCHAR(200) NOT NULL,
  UNIT VARCHAR(200) NOT NULL,
  BASELINE_VALUE DECIMAL(36,12) NOT NULL,
  OBSERVED_VALUE DECIMAL(36,12) NOT NULL,
  IMPACT_TYPE VARCHAR(200) NOT NULL,
  SCHEMA_VERSION VARCHAR(50) NOT NULL,
  PRIMARY KEY (KPI_ID),
  FOREIGN KEY (SCENARIO_INSTANCE_ID) REFERENCES OPS_STAGE.STG_SCENARIO_METADATA (SCENARIO_INSTANCE_ID),
  FOREIGN KEY (OBSERVATION_ID) REFERENCES OPS_STAGE.STG_DATASET_OBSERVATIONS (OBSERVATION_ID),
  FOREIGN KEY (DATASET_ID) REFERENCES OPS_STAGE.STG_DATASETS (DATASET_ID)
);

CREATE TABLE IF NOT EXISTS OPS_STAGE.STG_INCIDENT_HISTORY (
  INCIDENT_ID VARCHAR(200) NOT NULL,
  PIPELINE_ID VARCHAR(200) NOT NULL,
  SCENARIO_INSTANCE_ID VARCHAR(200) NOT NULL,
  OCCURRED_AT TIMESTAMP NOT NULL,
  INCIDENT_CATEGORY VARCHAR(200) NOT NULL,
  RESOLUTION_STATUS VARCHAR(200) NOT NULL,
  SCHEMA_VERSION VARCHAR(50) NOT NULL,
  PRIMARY KEY (INCIDENT_ID),
  FOREIGN KEY (PIPELINE_ID) REFERENCES OPS_STAGE.STG_PIPELINE_DEFINITIONS (PIPELINE_ID),
  FOREIGN KEY (SCENARIO_INSTANCE_ID) REFERENCES OPS_STAGE.STG_SCENARIO_METADATA (SCENARIO_INSTANCE_ID)
);
